import {installTrainingSchema} from './schema.js';
import {createTrainingService} from './service.js';
import {TrainingError} from './contract.js';
import {createQuizService} from './quiz-service.js';
import {createTrainingAssetService,trainingAssetScope} from './assets.js';
import {createCourseService} from './course-service.js';
import {certificateFor,certificateList,certificatePDF,revokeCertificate,verifyCertificate} from './certificates.js';
export {queueExpiringCertificates} from './certificates.js';
export {queueAssignmentReminders} from './reminders.js';
import {trainingAnalytics,trainingAnalyticsFilters} from './analytics.js';
import {providerCapabilities} from './video-providers.js';
import {createMuxSigner} from './mux-signer.js';
import {createMuxCatalogAdapter} from './mux-catalog.js';
import {createVideoCatalogService} from './video-catalog-service.js';
import {createVideoSessionService} from './video-session-service.js';
import {createVideoCheckService} from './video-check-service.js';
import {createVideoCheckpointService} from './video-checkpoint-service.js';
import {createVideoReviewService} from './video-review-service.js';
import {createOnboardingService} from './onboarding.js';
export {enrollNewTrainingEmployee,reconcileTrainingOnboarding} from './onboarding.js';
import {createRecurrenceService} from './recurrence.js';
export {runTrainingRecurrences} from './recurrence.js';
import {createAudienceGroupService} from './groups.js';
import {createQuestionBankService} from './question-banks.js';

export async function installTraining({app,pool,authRequired,storage=null,muxSigner=null,muxCatalog=null}){
  await installTrainingSchema(pool);
  const signer=muxSigner??createMuxSigner(),catalog=muxCatalog??createMuxCatalogAdapter();
  const videoCapabilities=providerCapabilities({muxSigningReady:signer.ready&&catalog.ready,
    knowledgeCheckReady:signer.ready&&catalog.ready,interactiveReady:signer.ready&&catalog.ready,
    highAssuranceReady:signer.ready&&catalog.ready});
  const service=createTrainingService({pool,videoCapabilities});
  const groups=createAudienceGroupService({pool});
  const quiz=createQuizService({pool});
  const questionBanks=createQuestionBankService({pool});
  const assets=createTrainingAssetService({pool,storage});
  const courses=createCourseService({pool});
  const unregisterScope=storage?.registerProtectedStorageScope?.('training',trainingAssetScope());
  const route=(method,path,fn)=>app[method]('/api/training'+path,authRequired,async(req,res)=>{
    res.set('Cache-Control','private, no-store');
    try{res.json(await fn(req));}
    catch(error){
      if(error instanceof TrainingError||(Number.isInteger(error?.status)&&error.status>=400&&error.status<500))res.status(error.status).json({error:error.code,message:error.message});
      else{console.error('[training]',error?.name||'error');res.status(503).json({error:'training_unavailable',message:'Training is temporarily unavailable. Please retry.'});}
    }
  });
  route('get','/definitions',r=>service.listDefinitions(r,r.query));
  route('get','/question-banks',r=>questionBanks.list(r));
  route('post','/question-banks',r=>questionBanks.create(r,r.body));
  route('get','/question-banks/:id',r=>questionBanks.get(r,r.params.id));
  route('put','/question-banks/:id',r=>questionBanks.update(r,r.params.id,r.body));
  route('post','/question-banks/:id/archive',r=>questionBanks.archive(r,r.params.id,r.body));
  route('post','/question-banks/:id/import',r=>questionBanks.import(r,r.params.id,r.body));
  route('get','/course-lesson-options',r=>service.lessonOptions(r));
  route('post','/definitions/validate',r=>service.validateDefinition(r,r.body));
  route('post','/definitions',r=>service.createDefinition(r,r.body));
  route('post','/definitions/import',r=>service.importDefinition(r,r.body));
  route('get','/definitions/:id',r=>service.getDefinition(r,r.params.id));
  route('get','/definitions/:id/export',r=>service.exportDefinition(r,r.params.id));
  route('post','/definitions/:id/duplicate',r=>service.duplicateDefinition(r,r.params.id,r.body));
  route('post','/definitions/:id/archive',r=>service.archiveDefinition(r,r.params.id,r.body));
  route('get','/definitions/:id/versions',r=>service.listDefinitionVersions(r,r.params.id));
  route('get','/definitions/:id/versions/:versionID',r=>service.getDefinitionVersion(r,r.params.id,r.params.versionID));
  route('put','/definitions/:id',r=>service.updateDefinition(r,r.params.id,r.body));
  route('post','/definitions/:id/publish',r=>service.publish(r,r.params.id,r.body));
  route('post','/assignments',r=>service.assign(r,r.body));
  route('get','/assignments',r=>service.listAssignments(r));
  route('get','/audience-groups',r=>groups.list(r));
  route('post','/audience-groups',r=>groups.create(r,r.body));
  route('get','/audience-groups/:id',r=>groups.get(r,r.params.id));
  route('put','/audience-groups/:id',r=>groups.update(r,r.params.id,r.body));
  route('post','/audience-groups/:id/archive',r=>groups.archive(r,r.params.id,r.body));
  route('post','/quick-tasks',r=>service.quickTask(r,r.body));
  route('post','/courses/validate',r=>courses.validate(r,r.body));
  route('get','/courses',r=>courses.list(r));
  route('get','/course-version-options',r=>courses.versionOptions(r));
  route('post','/courses',r=>courses.create(r,r.body));
  route('get','/courses/mine',r=>courses.mine(r));
  route('get','/courses/:id',r=>courses.get(r,r.params.id));
  route('put','/courses/:id',r=>courses.update(r,r.params.id,r.body));
  route('post','/courses/:id/publish',r=>courses.publish(r,r.params.id,r.body));
  route('post','/course-enrollments',r=>courses.assign(r,r.body));
  route('get','/course-enrollments/:id',r=>courses.enrollment(r,r.params.id));
  route('post','/course-enrollments/:id/lessons/:lessonId/start',r=>courses.startLesson(r,r.params.id,r.params.lessonId));
  route('get','/certificates/mine',r=>certificateList(pool,r));
  route('get','/certificates/verify/:code',r=>verifyCertificate(pool,r,r.params.code));
  route('get','/certificates/:id',r=>certificateFor(pool,r,r.params.id));
  route('post','/certificates/:id/revoke',r=>revokeCertificate(pool,r,r.params.id,r.body));
  route('get','/analytics',r=>trainingAnalytics(pool,r,r.query));
  route('get','/analytics/filters',r=>trainingAnalyticsFilters(pool,r));
  const videos=createVideoCatalogService({pool,catalog,signer,capabilities:videoCapabilities});
  const playback=createVideoSessionService({pool,signer});
  const videoChecks=createVideoCheckService({pool});
  const checkpoints=createVideoCheckpointService({pool});
  const videoReviews=createVideoReviewService({pool});
  const onboarding=createOnboardingService({pool});
  const recurrences=createRecurrenceService({pool});
  route('get','/video/providers',()=>videoCapabilities);
  route('post','/video/detect',r=>videos.detect(r,r.body));
  route('get','/video/assets',r=>videos.list(r));
  route('post','/video/assets/verify',r=>videos.verify(r,r.body));
  route('get','/recipients/:id/videos/:blockId/progress',r=>playback.progress(r,r.params.id,r.params.blockId));
  route('post','/recipients/:id/videos/:blockId/sessions',r=>playback.start(r,r.params.id,r.params.blockId));
  route('get','/video/sessions/:id',r=>playback.get(r,r.params.id));
  route('post','/video/sessions/:id/events',r=>playback.event(r,r.params.id,r.body));
  route('post','/video/sessions/:id/finish',r=>playback.finish(r,r.params.id));
  route('get','/recipients/:id/videos/:blockId/check',r=>videoChecks.get(r,r.params.id,r.params.blockId));
  route('post','/recipients/:id/videos/:blockId/check',r=>videoChecks.submit(r,r.params.id,r.params.blockId,r.body));
  route('get','/video/checks/:id/grade',r=>videoChecks.graderView(r,r.params.id));
  route('post','/video/checks/:id/grade',r=>videoChecks.grade(r,r.params.id,r.body));
  route('get','/recipients/:id/videos/:blockId/checkpoints',r=>checkpoints.list(r,r.params.id,r.params.blockId));
  route('post','/recipients/:id/videos/:blockId/checkpoints/:checkpointId',r=>checkpoints.submit(r,r.params.id,r.params.blockId,r.params.checkpointId,r.body));
  route('get','/video/checkpoints/:id/grade',r=>checkpoints.graderView(r,r.params.id));
  route('post','/video/checkpoints/:id/grade',r=>checkpoints.grade(r,r.params.id,r.body));
  route('get','/video/reviews',r=>videoReviews.list(r));
  route('get','/onboarding-policies',r=>onboarding.list(r));
  route('post','/onboarding-policies',r=>onboarding.create(r,r.body));
  route('post','/onboarding-policies/:id/disable',r=>onboarding.disable(r,r.params.id));
  route('get','/recurrences',r=>recurrences.list(r));
  route('post','/recurrences',r=>recurrences.create(r,r.body));
  route('post','/recurrences/:id/disable',r=>recurrences.disable(r,r.params.id));
  app.get('/api/training/certificates/:id/pdf',authRequired,async(req,res)=>{
    res.set('Cache-Control','private, no-store');
    try{const certificate=await certificateFor(pool,req,req.params.id);const pdf=await certificatePDF(certificate);
      res.set('Content-Type','application/pdf');res.set('Content-Disposition',`attachment; filename="${certificate.verification_code}.pdf"`);res.send(pdf);}
    catch(error){if(error instanceof TrainingError||(Number.isInteger(error?.status)&&error.status>=400&&error.status<500))res.status(error.status).json({error:error.code,message:error.message});
      else{console.error('[training-certificate]',error?.name||'error');res.status(503).json({error:'training_unavailable'});}}
  });
  route('post','/assets/reserve',r=>assets.reserve(r,r.body));
  route('get','/recipients/:id/assets',r=>assets.listRecipient(r,r.params.id));
  route('get','/eligible-recipients',r=>service.eligibleRecipients(r));
  route('get','/supervisors/:supervisorId',r=>service.listSupervision(r,r.params.supervisorId));
  route('put','/supervisors/:supervisorId/employees/:employeeId',r=>service.setSupervision(r,r.params.supervisorId,r.params.employeeId,r.body?.supervised));
  route('get','/mine',r=>service.listMine(r,r.query));
  route('get','/reviews',r=>service.listReviews(r,r.query));
  route('get','/managed',r=>service.listManaged(r,r.query));
  route('get','/recipients/:id',r=>service.getRecipient(r,r.params.id));
  route('get','/recipients/:id/history',r=>service.history(r,r.params.id));
  route('put','/recipients/:id/responses',r=>service.saveResponses(r,r.params.id,r.body));
  route('post','/recipients/:id/submit',r=>service.submit(r,r.params.id,r.body));
  route('post','/recipients/:id/review',r=>service.review(r,r.params.id,r.body));
  route('post','/recipients/:id/override',r=>service.overrideCompletion(r,r.params.id,r.body));
  route('get','/recipients/:id/quiz/attempts',r=>quiz.list(r,r.params.id));
  route('post','/recipients/:id/quiz/attempts',r=>quiz.start(r,r.params.id));
  route('get','/recipients/:id/quiz/review',r=>quiz.reviewForRecipient(r,r.params.id));
  route('get','/quiz/attempts/:id',r=>quiz.get(r,r.params.id));
  route('put','/quiz/attempts/:id/responses',r=>quiz.save(r,r.params.id,r.body));
  route('post','/quiz/attempts/:id/submit',r=>quiz.submit(r,r.params.id,r.body));
  route('get','/quiz/attempts/:id/grade',r=>quiz.graderView(r,r.params.id));
  route('post','/quiz/attempts/:id/grade',r=>quiz.grade(r,r.params.id,r.body));
  return {...service,stop:()=>unregisterScope?.()};
}
